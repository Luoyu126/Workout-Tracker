import { constants } from "node:fs";
import { access, readFile, writeFile } from "node:fs/promises";
import { basename } from "node:path";
import { fileURLToPath } from "node:url";

const maestroDir = new URL("./", import.meta.url);
const templateUrl = new URL("device-smoke-report-template.md", maestroDir);

function usage() {
  return [
    "Usage: npm run e2e:device-report:create -- <candidate> [--dry-run]",
    "",
    "Creates e2e/maestro/device-smoke-report-YYYYMMDD-<candidate>.md from",
    "device-smoke-report-template.md. Set DEVICE_SMOKE_REPORT_DATE=YYYYMMDD",
    "to make the date deterministic."
  ].join("\n");
}

function formatDate(value = new Date()) {
  const explicitDate = process.env.DEVICE_SMOKE_REPORT_DATE;
  if (explicitDate) {
    if (!/^\d{8}$/.test(explicitDate)) {
      throw new Error("DEVICE_SMOKE_REPORT_DATE must use YYYYMMDD format");
    }
    return explicitDate;
  }

  return value.toISOString().slice(0, 10).replaceAll("-", "");
}

function sanitizeCandidate(rawCandidate) {
  const candidate = rawCandidate.trim().toLowerCase().replace(/[^a-z0-9._-]+/g, "-").replace(/^-+|-+$/g, "");
  if (!candidate) {
    throw new Error("candidate must include at least one letter or number");
  }
  return candidate;
}

function renderReport(template, { candidate, reportDate }) {
  const generatedMetadata = [
    "> Generated by `npm run e2e:device-report:create`.",
    `> Candidate: \`${candidate}\`.`,
    `> Report date: \`${reportDate}\`.`,
    "> Source template: `device-smoke-report-template.md`.",
    ""
  ].join("\n");

  return template.replace("# Device Smoke Report\n\n", `# Device Smoke Report\n\n${generatedMetadata}`);
}

async function ensureReportDoesNotExist(targetUrl) {
  try {
    await access(targetUrl, constants.F_OK);
  } catch (error) {
    if (error && error.code === "ENOENT") {
      return;
    }
    throw error;
  }

  throw new Error(
    `Report already exists: ${basename(fileURLToPath(targetUrl))}. Delete or rename it, or choose a different candidate.`
  );
}

async function main() {
  const args = process.argv.slice(2);
  const isDryRun = args.includes("--dry-run");
  const candidateArg = args.find((arg) => arg !== "--dry-run");

  if (args.includes("--help") || args.includes("-h")) {
    console.log(usage());
    process.exit(0);
  }

  if (!candidateArg) {
    console.log(usage());
    process.exit(1);
  }

  const candidate = sanitizeCandidate(candidateArg);
  const reportDate = formatDate();
  const filename = `device-smoke-report-${reportDate}-${candidate}.md`;
  const targetUrl = new URL(filename, maestroDir);

  try {
    await access(templateUrl, constants.R_OK);
  } catch {
    throw new Error(`Missing template: ${basename(fileURLToPath(templateUrl))}`);
  }

  if (!isDryRun) {
    await ensureReportDoesNotExist(targetUrl);
    const template = await readFile(templateUrl, "utf-8");
    await writeFile(targetUrl, renderReport(template, { candidate, reportDate }), { flag: "wx" });
  }

  console.log(fileURLToPath(targetUrl));
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
